package com.louitarot.card.domain;

/**
 * 수트에 대응하는 4원소 (완드=불, 컵=물, 소드=공기, 펜타클=흙).
 *
 * 카드에 인쇄된 정보가 아니라 황금여명회 전통의 해석 체계에서 온 파생 속성으로,
 * 이 서비스에서는 케미 점수의 "원소 궁합" 계산에만 쓴다 ([[케미 점수 산출 로직]]).
 * 메이저 아르카나는 원소 궁합 계산 대상이 아니므로 null로 둔다 — 점성술 전통엔
 * 메이저에도 원소를 붙이는 체계가 있지만, 지금 점수 로직이 필요로 하지 않아서 모델링하지 않았다.
 */
public enum Element {
    FIRE,
    WATER,
    AIR,
    EARTH
}
